-- Полная структура базы service_tech.
-- Имена столбцов и связей такие, как их создаёт TypeORM.

CREATE TABLE public.roles (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role character varying(6) NOT NULL
);

CREATE TABLE public.appeal_status (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    st character varying(15) NOT NULL
);

CREATE TABLE public."POinfo" (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "TextInfo" character varying(255) NOT NULL
);

CREATE TABLE public.admins (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_admin character varying(10) NOT NULL,
    password character varying NOT NULL,
    password_plain character varying(10) NOT NULL,
    fio_admin character varying(60) NOT NULL,
    phone_number_admin character varying(12) NOT NULL,
    telegram_id character varying(200),
    vk_id character varying(200),
    email character varying(40),
    "roleId" integer,
    CONSTRAINT "FK_admins_role" FOREIGN KEY ("roleId") REFERENCES public.roles(id)
);

CREATE TABLE public.staffs (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_staff character varying(10) NOT NULL,
    password character varying NOT NULL,
    password_plain character varying(10) NOT NULL,
    fio_staff character varying(60) NOT NULL,
    phone_number_staff character varying(12),
    email character varying(40),
    telegram_id character varying(200),
    vk_id character varying(200),
    "roleId" integer,
    CONSTRAINT "FK_staffs_role" FOREIGN KEY ("roleId") REFERENCES public.roles(id)
);

CREATE TABLE public.clients (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_client character varying(10) NOT NULL,
    password_hash character varying NOT NULL,
    password_plain character varying(10) NOT NULL,
    phone_number_client character varying(12) NOT NULL,
    company_name character varying(50) NOT NULL,
    telegram_id character varying(200),
    vk_id character varying(200),
    email character varying(40),
    "roleId" integer,
    CONSTRAINT "FK_clients_role" FOREIGN KEY ("roleId") REFERENCES public.roles(id)
);

CREATE TABLE public.staff_clients (
    staff_id integer NOT NULL,
    client_id integer NOT NULL,
    CONSTRAINT "PK_staff_clients" PRIMARY KEY (staff_id, client_id),
    CONSTRAINT "FK_staff_clients_staff"
        FOREIGN KEY (staff_id) REFERENCES public.staffs(id)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT "FK_staff_clients_client"
        FOREIGN KEY (client_id) REFERENCES public.clients(id)
);

CREATE INDEX "IDX_staff_clients_staff_id" ON public.staff_clients (staff_id);
CREATE INDEX "IDX_staff_clients_client_id" ON public.staff_clients (client_id);

CREATE TABLE public.appeals (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mechanism character varying(25) NOT NULL,
    priority character varying(20) NOT NULL DEFAULT 'Средний',
    problem character varying(256) NOT NULL,
    fio_client character varying(60) NOT NULL,
    date_start timestamp NOT NULL,
    appeal_desc character varying(256),
    date_close timestamp,
    fio_staff character varying(60),
    "statusId" integer,
    "fioStaffCloseIdId" integer,
    "fioStaffOpenIdId" integer,
    "companyNameIdId" integer,
    CONSTRAINT "FK_appeals_status" FOREIGN KEY ("statusId") REFERENCES public.appeal_status(id),
    CONSTRAINT "FK_appeals_staff_close" FOREIGN KEY ("fioStaffCloseIdId") REFERENCES public.staffs(id),
    CONSTRAINT "FK_appeals_staff_open" FOREIGN KEY ("fioStaffOpenIdId") REFERENCES public.staffs(id),
    CONSTRAINT "FK_appeals_client" FOREIGN KEY ("companyNameIdId") REFERENCES public.clients(id)
);
